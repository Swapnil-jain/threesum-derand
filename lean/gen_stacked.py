def dec_ulp(s): return F(1, 10 ** len(s.split(".")[1]))

def terms(c, th, eps, tier):
    g = agamma(A(c), A(th), tier["boxes"])
    return [A(eps) * g, A(eps) * (A("1/2") - aq(A(th)))], g, aE(A(c), tier["enc"])

def sig_hi(c, th, eps, tier):
    """Upper bound on sigma: the smallest term's upper end, rounded UP (outward) at Q_DIGITS."""
    ts, _, _ = terms(c, th, eps, tier)
    j = min(range(2), key=lambda i: hi_of(ts[i]))
    return j, ceil_dec(hi_of(ts[j]), Q_DIGITS) + F(1, 10 ** Q_DIGITS), lo_of(min(ts, key=lambda t: lo_of(t)))

def bounds_lemma(name, c, th, eps, tier, doc):
    """One lemma with outward rational bounds on gamma, q and E at (c, th): the only place the logs are bounded."""
    P = Point()
    pc, pth = Param(c), Param(th)
    g = need_gamma(P, pc, pth, tier["boxes"]); need_q(P, pth); E = need_E(P, pc, tier["enc"])
    body = P.lines()
    qs = [q for q in P.qs]
    # q0, q1, q2 are gamma, q, E in that order (need_gamma, need_q, need_E)
    conj, names = [], []
    for i, (term, unfold, L, val) in enumerate(qs):
        lo = floor_dec(lo_of(val), Q_DIGITS) - F(1, 10 ** Q_DIGITS)
        hi = ceil_dec(hi_of(val), Q_DIGITS) + F(1, 10 ** Q_DIGITS)
        conj += [f"({lean_q(lo)} : ℝ) ≤ {term}", f"{term} ≤ ({lean_q(hi)} : ℝ)"]
        names += [f"q{i}l", f"q{i}h"]
    stmt = " ∧\n    ".join(conj)
    out = f"/-- {doc} -/\ntheorem {name} :\n    {stmt} := by\n{body}"
    out += "  exact ⟨" + ", ".join(names) + "⟩\n"
    return out, g, E

def ty(c, th, eps, g, E, s0, bA, oA):
    return (f"CertStacked {Param(c).lean} {Param(th).lean} {Param(eps).lean} {g} {E} "
            f"({lean_q(F(s0))}) ({lean_q(F(bA))}) ({lean_q(F(oA))})")

def sig_expr(th, eps, g): return f"sigStacked {Param(th).lean} {Param(eps).lean} {g}"

BND = "  obtain ⟨g1, g2, q1, q2, e1, e2⟩ := {b}\n"
TERM = ("  have hm := minl_le (show {t} ∈ stTerms {th} {eps} {g} by simp [stTerms])\n"
        "  unfold sigStacked\n")

