def gen_stacked():
    out = STACKED_HEADER
    for T in TIERS:
        tg, c, th, eps = T["tag"], T["c"], T["th"], T["eps"]
        b, g, E = bounds_lemma(f"stacked_{tg}_bounds", c, th, eps, T,
                               f"Bounds on gamma, q, E at the stacked_cert.py point, {T['name']}.")
        out += b + "\n"
        ts, ga, ea = terms(c, th, eps, T)
        # the claims hold on the whole arb ball
        s_lo = lo_of(gen.certify.bmin(*ts))
        assert s_lo >= F(T["s0"]) and 3 - s_lo <= F(T["bA"]) and 3 - s_lo < F(T["oA"]), tg
        thL, epsL = Param(th).lean, Param(eps).lean
        bnd = BND.format(b=f"stacked_{tg}_bounds")
        out += (f"/-- stacked_cert.py, {T['name']}: Theorem A', det all-edges ET, (min,+), APSP O(n^{T['oA']}). -/\n"
                f"theorem stacked_{tg} : {ty(c, th, eps, g, E, T['s0'], T['bA'], T['oA'])} := by\n{bnd}"
                f"  apply CertStacked.mk'\n"
                f"  all_goals first\n    | (norm_num; done)\n    | linarith\n"
                f"    | (intro t ht; simp only [stTerms, List.mem_cons, List.mem_nil_iff, or_false] at ht\n"
                f"       rcases ht with rfl | rfl <;> linarith)\n\n")
        j, hi, _ = sig_hi(c, th, eps, T)
        assert hi < F(T["s0"]) + dec_ulp(T["s0"])
        tj = [f"{epsL} * {g}", f"{epsL} * (1 / 2 - qExp {thL})"][j]
        out += (f"/-- Upper bound on sigma at the {tg} point, through its binding term. -/\n"
                f"theorem stacked_{tg}_sigma_le : {sig_expr(th, eps, g)} ≤ ({lean_q(hi)} : ℝ) := by\n{bnd}"
                + TERM.format(t=tj, th=thL, eps=epsL, g=g) + "  linarith\n\n")
        # negative controls through the upper bound
        s0n = lean_q(F(T["s0"]) + dec_ulp(T["s0"]))
        bAn = lean_q(F(T["bA"]) - dec_ulp(T["bA"]))
        oAn = lean_q(F(T["oA"]) - dec_ulp(T["oA"]))
        assert 3 - F(bAn) > hi and 3 - F(oAn) >= hi
        for nm, (s0, bA, oA), fld, doc in [
                ("next_s0", (s0n, T["bA"], T["oA"]), "saving", f"Next grid point: s0 + {lean_q(dec_ulp(T['s0']))} must fail."),
                ("next_bA", (T["s0"], bAn, T["oA"]), "apsp", f"Next grid point: bA - {lean_q(dec_ulp(T['bA']))} must fail."),
                ("next_oA", (T["s0"], T["bA"], oAn), "apsp_O", f"Next grid point: oA - {lean_q(dec_ulp(T['oA']))} must fail.")]:
            out += (f"/-- {doc} -/\ntheorem stacked_{tg}_fails_{nm} : ¬ ({ty(c, th, eps, g, E, s0, bA, oA)}) := by\n"
                    f"  intro h\n  linarith [h.{fld}, stacked_{tg}_sigma_le]\n\n")
        # perturbed theta: the direction that lowers sigma most
        thv, u = F(th), F(1, 10 ** 6)
        best = None
        for sgn in (1, -1):
            th2 = lean_q(thv + sgn * u)
            j2, hi2, _ = sig_hi(c, th2, eps, T)
            if hi2 < F(T["s0"]) and (best is None or hi2 < best[1]): best = (th2, hi2, j2, sgn)
        assert best, tg
        th2, hi2, j2, sgn = best
        b2, g2, E2 = bounds_lemma(f"stacked_{tg}_perturbed_bounds", c, th2, eps, T,
                                  f"Bounds on gamma, q, E at the perturbed point theta = {th2}.")
        out += b2 + "\n"
        th2L = Param(th2).lean
        tj2 = [f"{epsL} * {g2}", f"{epsL} * (1 / 2 - qExp {th2L})"][j2]
        out += (f"/-- Perturbed parameter: theta = {th2} ({'+' if sgn > 0 else '-'}10^-6) must fail. -/\n"
                f"theorem stacked_{tg}_fails_perturbed : ¬ ({ty(c, th2, eps, g2, E2, T['s0'], T['bA'], T['oA'])}) := by\n"
                + BND.format(b=f"stacked_{tg}_perturbed_bounds")
                + "  intro h\n  have hs := h.saving\n"
                + TERM.format(t=tj2, th=th2L, eps=epsL, g=g2).replace("  unfold sigStacked\n", "  unfold sigStacked at hs\n")
                + "  linarith\n\n")
        assert A(eps) * ea > 1
        out += (f"/-- At the {tg} point `eps E > 1`: the unfolded instance's encoding term `1 - eps E` is negative, so "
                f"these exponents need Lemma 3.2'. -/\n"
                f"theorem stacked_{tg}_unfolded_enc_neg : (1 : ℝ) < {epsL} * {E} := by\n{bnd}  linarith\n\n")
    out += "end TS\n"
    open(os.path.join(HERE, "ThreesumLean", "Stacked.lean"), "w").write(out)

def gen_kclique():
    out = KCLIQUE_HEADER
    for T in TIERS:
        tg, c, th, eps = T["tag"], T["c"], T["th"], T["eps"]
        pc, pth = Param(c), Param(th)
        g = f"(gammaExact {pc.lean} {pth.lean})" if T["boxes"] == "exact" else f"(gammaRho {pc.lean} {pth.lean})"
        sig = f"({sig_expr(th, eps, g)})"
        s0, s6 = F(T["s0"]), F(T["s6"])
        _, hi, _ = sig_hi(c, th, eps, T)
        assert s6 < s0
        get = f"  have hlo := stacked_{tg}.saving\n  have hhi := stacked_{tg}_sigma_le\n"
        out += (f"/-- {T['name']}: det Zero/Min/Max-Weight k-Clique in O(n^(k - {T['s6']} floor(k/3))) for every "
                f"k >= 3. -/\n"
                f"theorem kclique_{tg}_uniform : ∀ k : ℕ, 3 ≤ k →\n"
                f"    kcExp k {sig} < (k : ℝ) - ((k / 3 : ℕ) : ℝ) * ({lean_q(s6)}) := by\n"
                f"  intro k hk\n{get}  exact kcExp_lt (by linarith) hk\n\n")
        conj = []
        for k, e in T["kc"].items():
            assert k - (k // 3) * s0 <= F(e), (tg, k)
            conj.append(f"kcExp {k} {sig} ≤ ({lean_q(F(e))})")
        out += (f"/-- {T['name']}: the printed k-Clique exponents for k = 3..12 (rounded up). -/\n"
                f"theorem kclique_{tg}_table :\n    " + " ∧\n    ".join(conj) + " := by\n"
                f"{get}  unfold kcExp\n  norm_num\n  refine ⟨{', '.join(['?_'] * len(conj))}⟩ <;> linarith\n\n")
        det3 = {"T4": "1996001/1000000", "T1": "1996291/1000000"}[tg]
        assert 2 - s0 / 2 <= F(T["conv"]) and F(T["conv"]) > F(det3) and 2 - hi / 2 > F(det3)
        out += (f"/-- {T['name']}: Convolution-3SUM through Exact Triangle on n^(1/2) vertices, `2 - sigma/2 <= "
                f"{T['conv']}`, is worse than det 3SUM's {float(F(det3))}. -/\n"
                f"theorem conv3sum_via_ET_{tg} : 2 - {sig} / 2 ≤ ({lean_q(F(T['conv']))}) ∧\n"
                f"    ({det3} : ℝ) < 2 - {sig} / 2 := by\n{get}  constructor <;> linarith\n\n")
        # controls
        s6n = s6 + dec_ulp(T["s6"])
        assert hi < s6n
        out += (f"/-- Control: the uniform form at s6 + {lean_q(dec_ulp(T['s6']))} fails (at k = 3). -/\n"
                f"theorem kclique_{tg}_uniform_fails_next : ¬ (∀ k : ℕ, 3 ≤ k →\n"
                f"    kcExp k {sig} < (k : ℝ) - ((k / 3 : ℕ) : ℝ) * ({lean_q(s6n)})) := by\n"
                f"  intro h\n  have h3 := h 3 le_rfl\n{get}  unfold kcExp at h3\n  norm_num at h3\n  linarith\n\n")
        e12n = F(T["kc"][12]) - dec_ulp(T["kc"][12])
        assert 12 - 4 * hi > e12n
        out += (f"/-- Control: the k = 12 exponent one unit lower ({float(e12n)}) fails. -/\n"
                f"theorem kclique_{tg}_fails_next_12 : ¬ (kcExp 12 {sig} ≤ ({lean_q(e12n)})) := by\n"
                f"  intro h\n{get}  unfold kcExp at h\n  norm_num at h\n  linarith\n\n")
    out += "end TS\n"
    open(os.path.join(HERE, "ThreesumLean", "KClique.lean"), "w").write(out)

if __name__ == "__main__":
    gen_stacked(); gen_kclique()
