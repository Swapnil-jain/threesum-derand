"""Generate ThreesumLean/Stacked.lean and ThreesumLean/KClique.lean: kernel checks of the folded (stacked) all-edges
Exact Triangle certificate (stacked_cert.py) and of its k-Clique corollary (stacked_cert.py).

Same method as gen.py: arb (python-flint) only chooses the rational bounds; every log atom is bounded by `log_mem`
(series bound checked by the kernel), gamma, q and E are bounded from the atoms by linarith, and each printed claim
is a theorem. Points, claims and controls below are copied from the scripts' output (both re-run, output unchanged).
Usage: python lean/gen_stacked.py
"""
